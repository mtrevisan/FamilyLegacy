	/**
	 * @param context	The context: the model and the window the dialog belongs to.
	 * @param view	What the dashboard shows first.
	 */
	public TaskDashboardDialog(final ToolContext context, final TaskBoard.View view){
		this(context, view, LocalDate::now);
	}

	/** @param today	What day it is (the tests fix it). */
	TaskDashboardDialog(final ToolContext context, final TaskBoard.View view, final Supplier<LocalDate> today){
		super(context.owner(), I18N.t("dialog.task_dashboard.title"), ModalityType.APPLICATION_MODAL);

		this.context = Objects.requireNonNull(context, "context");
		this.today = Objects.requireNonNull(today, "today");

		setLayout(new BorderLayout(6, 6));
		add(createNorth(view), BorderLayout.NORTH);
		add(createCenter(), BorderLayout.CENTER);
		add(createSouth(), BorderLayout.SOUTH);

		setPreferredSize(new Dimension(1100, 640));
		ToolDialogs.installEscapeToClose(this);
		pack();
		setLocationRelativeTo(context.owner());

		reload();
	}


