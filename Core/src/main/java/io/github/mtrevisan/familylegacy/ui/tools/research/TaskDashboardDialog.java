	/** The rows of the table: one task each, the texts computed once. */
	private static final class TaskTableModel extends AbstractTableModel{

		private transient List<TaskBoard.Entry> entries = List.of();
		private transient List<Object[]> rows = List.of();


		void setEntries(final List<TaskBoard.Entry> entries, final FLEFModel model){
			this.entries = List.copyOf(entries);
			final List<Object[]> texts = new ArrayList<>(entries.size());
			for(final TaskBoard.Entry entry : entries)
				texts.add(texts(entry, model));
			rows = texts;
			fireTableDataChanged();
		}

		private static Object[] texts(final TaskBoard.Entry entry, final FLEFModel model){
			final StringJoiner about = new StringJoiner("; ");
			for(final String id : entry.relatedIds()){
				final FLEFRecord record = (model != null? model.getRecordById(id): null);
				about.add(record != null? RecordDisplay.describe(record, model): id);
			}
			return new Object[]{
				(entry.due() != null? entry.due().toString(): StringUtils.EMPTY),
				new Ranked(priorityLabel(entry.priority()), OpenTasks.priorityRank(entry.priority())),
				statusLabel(entry.status()),
				StringUtils.defaultIfBlank(entry.description(), entry.record().getId()),
				about.toString(),
				(entry.isGenerated()? I18N.t("dialog.task_dashboard.column.source.assistant"): StringUtils.EMPTY)
			};
		}

		@Override
		public int getRowCount(){
			return rows.size();
		}

		@Override
		public int getColumnCount(){
			return COLUMN_KEYS.length;
		}

		@Override
		public String getColumnName(final int column){
			return I18N.t(COLUMN_KEYS[column]);
		}

		@Override
		public Object getValueAt(final int row, final int column){
			return rows.get(row)[column];
		}

	}


	/** Writes the due date of an overdue task in red, a task that is over in grey, and shows the whole text of a cell as its tooltip. */
	private final class TaskRenderer extends DefaultTableCellRenderer{

		@Override
		public Component getTableCellRendererComponent(final JTable table, final Object value, final boolean isSelected,
				final boolean hasFocus, final int row, final int column){
			super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

			final int modelRow = table.convertRowIndexToModel(row);
			final TaskBoard.Entry entry = (modelRow < tableModel.entries.size()? tableModel.entries.get(modelRow): null);
			final boolean overdue = (entry != null && entry.isOverdue(today.get()));
			final boolean over = (entry != null && !entry.isOpen());
			if(isSelected)
				setForeground(table.getSelectionForeground());
			else if(overdue)
				setForeground(ToolDialogs.ERROR_COLOR);
			else if(over)
				setForeground(UIManager.getColor("Label.disabledForeground"));
			else
				setForeground(table.getForeground());
			setFont(table.getFont().deriveFont(overdue && column == COLUMN_DUE? Font.BOLD: Font.PLAIN));

			final String text = (value != null? value.toString(): StringUtils.EMPTY);
			setToolTipText(StringUtils.isNotBlank(text) && (column == COLUMN_DESCRIPTION || column == COLUMN_ABOUT)? text: null);
			return this;
		}

	}

