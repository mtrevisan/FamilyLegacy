/**
 * The research tasks of the whole file in one place: the inbox of the tasks generated by the Research Assistant (to accept or to
 * dismiss), what is still to be done, what is over, and how far the work is (a count by status, the overdue ones, the share completed).
 * <p>
 * The tasks are filtered by view, priority, who wrote them, the kind of record they are about, overdue, and a text. A double click (or
 * <em>Edit</em>) opens the editor of the task, <em>Mark as</em> changes its status without opening it (completion tracking), and
 * <em>Open record</em> goes to a record the task is about (not only to its questions). The tasks are listed again after every change.
 * </p>
 */
