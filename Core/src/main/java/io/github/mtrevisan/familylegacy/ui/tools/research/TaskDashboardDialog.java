	private static <T> T value(final JComboBox<Choice<T>> combo){
		@SuppressWarnings("unchecked")
		final Choice<T> choice = (Choice<T>)combo.getSelectedItem();
		return (choice != null? choice.value(): null);
	}

	private <T> void selectValue(final JComboBox<Choice<T>> combo, final T value){
		for(int i = 0; i < combo.getItemCount(); i ++)
			if(Objects.equals(combo.getItemAt(i).value(), value)){
				combo.setSelectedIndex(i);
				return;
			}
	}


