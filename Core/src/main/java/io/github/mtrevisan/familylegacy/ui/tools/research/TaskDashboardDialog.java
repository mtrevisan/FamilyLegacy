	/** @return	What the filters say. */
	TaskBoard.Filter filter(){
		final TaskBoard.View view = value(viewCombo);
		return view.filter()
			.withPriority(value(priorityCombo))
			.withOrigin(view == TaskBoard.View.INBOX? TaskBoard.Origin.GENERATED: value(originCombo))
			.withOverdueOnly(overdueOnly.isSelected())
			.withRelatedType(value(relatedCombo))
			.withText(searchBox.query());
	}

	/** Builds the list again from the model (call it on the event dispatch thread), keeping the selected task selected. */
	void reload(){
		final TaskBoard.Entry previous = selected();
		final String previousId = (previous != null? previous.record().getId(): null);

		final FLEFModel model = context.model();
		final LocalDate day = today.get();
		final List<TaskBoard.Entry> all = (model != null? TaskBoard.list(model): List.of());
		final List<TaskBoard.Entry> shown = (model != null? TaskBoard.filter(all, filter(), model, day): List.of());

		loading = true;
		try{
			tableModel.setEntries(shown, model);
			for(int row = 0; previousId != null && row < shown.size(); row ++)
				if(previousId.equals(shown.get(row).record().getId())){
					final int viewRow = table.convertRowIndexToView(row);
					table.getSelectionModel().setSelectionInterval(viewRow, viewRow);
					break;
				}
		}
		finally{
			loading = false;
		}

		updateSummary(TaskBoard.statistics(all, day), shown.size());
		selectionChanged();
	}

	private void updateSummary(final TaskBoard.Statistics statistics, final int shown){
		final StringJoiner text = new StringJoiner(", ");
		text.add(I18N.tf("dialog.task_dashboard.summary", statistics.total(), statistics.open(), statistics.inProgress(),
			statistics.completed(), statistics.abandoned()));
		if(statistics.overdue() > 0)
			text.add(I18N.tf("dialog.task_dashboard.summary.overdue", statistics.overdue()));
		if(statistics.inbox() > 0)
			text.add(I18N.tf("dialog.task_dashboard.summary.inbox", statistics.inbox()));
		summary.setText(text.toString());
		summary.setForeground(statistics.overdue() > 0? ToolDialogs.ERROR_COLOR: UIManager.getColor("Label.foreground"));

		final int percent = (int)Math.round(statistics.completion() * 100.);
		completion.setValue(percent);
		completion.setString(I18N.tf("dialog.task_dashboard.completion", percent));
		footer.setText(I18N.tf("dialog.task_dashboard.shown", shown, statistics.total()));
	}

	private void selectionChanged(){
		final TaskBoard.Entry entry = selected();
		details.setText(describe(entry));
		details.setCaretPosition(0);
		acceptButton.setEnabled(entry != null && entry.isInInbox());
		dismissButton.setEnabled(entry != null && entry.isInInbox());
		markButton.setEnabled(entry != null);
		editButton.setEnabled(entry != null);
		openRecordButton.setEnabled(entry != null && !records(entry).isEmpty());
	}

	private String describe(final TaskBoard.Entry entry){
		if(entry == null)
			return StringUtils.EMPTY;

		final FLEFModel model = context.model();
		final StringBuilder sb = new StringBuilder();
		append(sb, "description", entry.description());
		append(sb, "status", statusLabel(entry.status()));
		append(sb, "priority", priorityLabel(entry.priority()));
		append(sb, "due", (entry.due() != null? entry.due().toString(): null));
		append(sb, "rationale", entry.rationale());
		append(sb, "outcome", entry.outcome());
		final StringJoiner questions = new StringJoiner("; ");
		for(final FLEFRecord question : entry.questions())
			questions.add(ResearchHelper.questionTitle(question));
		append(sb, "questions", questions.toString());
		final StringJoiner about = new StringJoiner("; ");
		for(final FLEFRecord record : records(entry))
			about.add(RecordDisplay.describe(record, model));
		append(sb, "about", about.toString());
		append(sb, "source", (entry.isGenerated()? I18N.t("dialog.task_dashboard.origin.generated"): null));
		append(sb, "id", entry.record().getId());
		return sb.toString();
	}

	private static void append(final StringBuilder sb, final String field, final String value){
		if(StringUtils.isNotBlank(value))
			sb.append(I18N.l("dialog.task_dashboard.detail." + field))
				.append(StringUtils.SPACE)
				.append(value)
				.append("\n\n");
	}

	/** @return	The records a task is about that exist (the ones it names and the ones of its questions). */
	private List<FLEFRecord> records(final TaskBoard.Entry entry){
		final FLEFModel model = context.model();
		final List<FLEFRecord> records = new ArrayList<>();
		for(final String id : entry.relatedIds()){
			final FLEFRecord record = (model != null? model.getRecordById(id): null);
			if(record != null)
				records.add(record);
		}
		return records;
	}


	/* ======================================================================
	 *                          Acting
	 * ====================================================================== */

	private TaskBoard.Entry selected(){
		final int viewRow = table.getSelectedRow();
		final int row = (viewRow >= 0? table.convertRowIndexToModel(viewRow): -1);
		return (row >= 0 && row < tableModel.entries.size()? tableModel.entries.get(row): null);
	}

	private void showPopup(final MouseEvent e){
		if(!e.isPopupTrigger())
			return;

		final int row = table.rowAtPoint(e.getPoint());
		if(row < 0)
			return;

		table.getSelectionModel().setSelectionInterval(row, row);
		final TaskBoard.Entry entry = selected();
		if(entry != null){
			final JPopupMenu menu = new JPopupMenu();
			final JMenuItem edit = new JMenuItem(I18N.t("panel.tasks.menu.edit"));
			edit.addActionListener(event -> editSelected());
			menu.add(edit);
			menu.addSeparator();
			addStatusItems(menu, entry);
			final List<JMenuItem> items = recordItems(entry);
			if(!items.isEmpty()){
				menu.addSeparator();
				for(final JMenuItem item : items)
					menu.add(item);
			}
			menu.show(table, e.getX(), e.getY());
		}
	}

	/** @return	The menu that changes the status of a task (the current one is disabled). */
	JPopupMenu createStatusMenu(final TaskBoard.Entry entry){
		final JPopupMenu menu = new JPopupMenu();
		addStatusItems(menu, entry);
		return menu;
	}

	private void addStatusItems(final JPopupMenu menu, final TaskBoard.Entry entry){
		for(final String status : ResearchTaskReader.STATUSES){
			final JMenuItem item = new JMenuItem(I18N.tf("panel.tasks.menu.mark", statusLabel(status)));
			item.setEnabled(!status.equalsIgnoreCase(entry.status()));
			item.addActionListener(e -> changeStatus(entry, status));
			menu.add(item);
		}
	}

	/** @return	The menu that opens one of the records a task is about, then one of its questions. */
	JPopupMenu createRecordsMenu(final TaskBoard.Entry entry){
		final JPopupMenu menu = new JPopupMenu();
		for(final JMenuItem item : recordItems(entry))
			menu.add(item);
		return menu;
	}

	private List<JMenuItem> recordItems(final TaskBoard.Entry entry){
		final FLEFModel model = context.model();
		final List<JMenuItem> items = new ArrayList<>();
		for(final FLEFRecord record : records(entry)){
			final JMenuItem item = new JMenuItem(I18N.tf("dialog.task_dashboard.open", RecordDisplay.describe(record, model)));
			item.addActionListener(e -> {
				ToolDialogs.openRecordEditor(this, model, record);
				reload();
			});
			items.add(item);
		}
		return items;
	}

	private void changeSelectedStatus(final String status){
		final TaskBoard.Entry entry = selected();
		if(entry != null)
			changeStatus(entry, status);
	}

	/** Changes the status of a task, as the menu does, and lists the tasks again. */
	void changeStatus(final TaskBoard.Entry entry, final String status){
		String outcome = null;
		//what came out of a task that is over is asked for once, if it has none (cancelling leaves the task as it is)
		if(entry.outcome() == null && (ResearchTaskReader.ENUM_STATUS_COMPLETED.equals(status)
				|| ResearchTaskReader.ENUM_STATUS_ABANDONED.equals(status))){
			final Optional<String> answer = outcomeAsker.apply(entry);
			if(answer.isEmpty())
				return;
			outcome = answer.get();
		}
		if(OpenTasks.changeStatus(entry.record(), status, outcome))
			reload();
	}

	private Optional<String> askOutcome(final TaskBoard.Entry entry){
		final String answer = JOptionPane.showInputDialog(this, I18N.t("dialog.task_dashboard.outcome"),
			I18N.t("dialog.task_dashboard.outcome.title"), JOptionPane.QUESTION_MESSAGE);
		return Optional.ofNullable(answer);
	}

	/** Replaces what asks for the outcome of a task that is over (the tests cannot answer a modal dialog); empty means cancel. */
	void setOutcomeAsker(final Function<TaskBoard.Entry, Optional<String>> outcomeAsker){
		this.outcomeAsker = Objects.requireNonNull(outcomeAsker, "outcomeAsker");
	}

	private void editSelected(){
		final TaskBoard.Entry entry = selected();
		if(entry == null)
			return;

		final var dialog = ResearchTaskHandler.getInstance()
			.createEditDialog(this, context.model(), entry.record());
		if(dialog != null){
			dialog.setVisible(true);
			reload();
		}
	}


	/* ======================================================================
	 *                          Testing
	 * ====================================================================== */

	/** @return	The tasks listed, in their order. */
	List<TaskBoard.Entry> shownEntries(){
		return List.copyOf(tableModel.entries);
	}

	/** @return	The ids of the tasks as listed after sorting by a column (ascending). */
	List<String> sortedBy(final int column){
		table.getRowSorter().setSortKeys(List.of(new javax.swing.RowSorter.SortKey(column, javax.swing.SortOrder.ASCENDING)));
		final List<String> ids = new ArrayList<>();
		for(int row = 0; row < table.getRowCount(); row ++)
			ids.add(tableModel.entries.get(table.convertRowIndexToModel(row)).record().getId());
		return ids;
	}

