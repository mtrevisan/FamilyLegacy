package io.github.mtrevisan.familylegacy.dossier;

import io.github.mtrevisan.familylegacy.io.model.FLEFModel;
import io.github.mtrevisan.familylegacy.io.model.readers.IndividualAttributeReader;
import io.github.mtrevisan.familylegacy.io.model.readers.IndividualReader;
import io.github.mtrevisan.familylegacy.io.model.readers.NoteReader;
import io.github.mtrevisan.familylegacy.io.model.record.FLEFRecord;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;


/** A note of the dossier tells which event, attribute or relationship it belongs to. */
class DossierNoteOwnerTest{

	@Test
	void theNoteOfAnAttributeNamesTheAttribute(){
		final FLEFModel model = new FLEFModel();
		model.addRecord(FLEFRecord.createMainRecord("I1", IndividualReader.TYPE));
		model.addRecord(FLEFRecord.createMainRecord("IA1", IndividualAttributeReader.TYPE)
			.addChild(FLEFRecord.createChildWithTagAndValue(IndividualAttributeReader.TAG_INDIVIDUAL, "I1"))
			.addChild(FLEFRecord.createChildWithTagAndValue(IndividualAttributeReader.TAG_TYPE, "occupation"))
			.addChild(FLEFRecord.createChildWithTagAndValue(IndividualAttributeReader.TAG_VALUE, "baker"))
			.addChild(FLEFRecord.createChildWithTag(NoteReader.TAG_NOTE)
				.addChild(FLEFRecord.createChildWithTagAndValue(NoteReader.TAG_TITLE, "A title"))));

		final DossierEntry note = new IndividualDossierService(model).build("I1")
			.entriesOf(DossierSectionType.NOTES)
			.getFirst();

		Assertions.assertEquals("A title", note.value());
		Assertions.assertTrue(note.subtitle().startsWith("of occupation: baker"), note.subtitle());
	}

}
