package io.github.mtrevisan.familylegacy.reports;


/** What a report shows of the preferred image of a person, that may be a part of a picture (a crop). */
public enum PortraitMode{

	/** The whole picture, with the region the portrait is told by in the caption. */
	WHOLE,
	/** Only the region of the portrait (the picture itself stays in the media). */
	CROP,
	/** Only the region of the portrait, and the picture is left out of the media. */
	CROP_WITHOUT_ORIGINAL

}
