package io.github.mtrevisan.familylegacy.reports;

import io.github.mtrevisan.familylegacy.io.model.FLEFModel;
import io.github.mtrevisan.familylegacy.io.model.record.FLEFRecord;
import io.github.mtrevisan.familylegacy.reports.i18n.ReportLabels;
import io.github.mtrevisan.reports.ReportDocument;
import io.github.mtrevisan.reports.ReportSection;
import org.apache.commons.lang3.StringUtils;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;


/**
 * Composes a book out of the reports of the application: every report is generated by {@link ReportBuilder}, as the report dialog does,
 * and its sections are put after the ones of the previous report, one level down (the report is a chapter of the book, what it tells is
 * a section of the chapter). Nothing of a report is written again here.
 * <p>
 * The result is a single {@link ReportDocument}, so every renderer writes it as it writes a report: the table of contents is made from
 * the headings, and the pages (PDF, Word) are numbered from the first to the last, whatever the report they belong to.
 * </p>
 * <p>
 * The reports are generated one at a time and only what the indexes need is kept of one report once it is in the book. The document
 * itself is in memory, as the one of every report is.
 * </p>
 */
public final class BookBuilder{

	/** The share of the progress kept for the front matter (the rest is for the reports and the indexes). */
	private static final int FRONT_PERCENT = 3;
	private static final int INDEXES_PERCENT = 5;
	/** The deepest level of a heading. */
	private static final int MAX_LEVEL = 6;
	/** A record reference in a link, {@code [text](@I12@)}. */
	private static final Pattern LINKED_ID = Pattern.compile("@([A-Za-z]+\\d+)@");
	/** A record reference in the text, {@code [I12]}. */
	private static final Pattern BRACKETED_ID = Pattern.compile("\\[([A-Za-z]+\\d+)]");


	private BookBuilder(){}


	/**
	 * Assembles the document of a book.
	 *
	 * @param model	The model to report on.
	 * @param book	The definition of the book.
	 * @param listener	Told how far the generation is.
	 * @return	The document, never {@code null}.
	 * @throws IllegalArgumentException	If the book has no reports, or a report is about a record that is not in the model.
	 */
	public static ReportDocument build(final FLEFModel model, final BookDefinition book, final ReportProgressListener listener){
		if(book.entries().isEmpty())
			throw new IllegalArgumentException("A book needs at least one report");

		final ReportLabels labels = new ReportLabels(book.language(), book.entries().getFirst().config().dateFormat());
		final Locale locale = labels.language().locale();
		final String title = (book.title().isEmpty()? labels.sections().bookTitle(): book.title());
		final Set<BookIndex> indexes = book.indexes();

		final List<ReportSection> sections = new ArrayList<>();
		//the first page break ends the page of the title (see ReportDocument): the cover
		if(book.coverPage())
			sections.add(ReportSection.PageBreak.INSTANCE);
		if(book.titlePage())
			appendTitlePage(sections, title, book);
		if(!book.prefaceText().isEmpty())
			appendPreface(sections, labels, book);
		listener.onProgress(FRONT_PERCENT, null);

		final Harvest harvest = new Harvest();
		final int count = book.entries().size();
		final int reportsPercent = 100 - FRONT_PERCENT - INDEXES_PERCENT;
		for(int i = 0; i < count; i ++){
			if(Thread.currentThread().isInterrupted())
				throw new RuntimeException("Report generation cancelled");

			final BookEntry entry = book.entries().get(i);
			final FLEFRecord root = rootOf(model, entry);
			final int from = FRONT_PERCENT + i * reportsPercent / count;
			final int to = FRONT_PERCENT + (i + 1) * reportsPercent / count;

			final ReportDocument report = ReportBuilder.build(entry.type(), model, root, configFor(entry, book),
				(percent, message) -> listener.onProgress(from + percent * (to - from) / 100, message));
			compose(sections, report, entry, labels, indexes, harvest);
			listener.onProgress(to, null);
		}

		appendIndexes(sections, model, labels, locale, indexes, harvest);
		listener.onProgress(100, null);

		return new ReportDocument(title, (book.subtitle().isEmpty()? null: book.subtitle()), sections, locale.toLanguageTag(),
			labels.sections().contents());
	}


	/** @return	The record a report is about, {@code null} if it is about the whole file. */
	private static FLEFRecord rootOf(final FLEFModel model, final BookEntry entry){
		if(entry.subjectId() == null)
			return null;

		final FLEFRecord root = model.getRecordById(entry.subjectId());
		if(root == null)
			throw new IllegalArgumentException("The record " + entry.subjectId() + " of the report " + entry.type() + " is not in the file");
		return root;
	}

	/**
	 * @return	The options of a report of the book: the ones the user gave it, in the language of the book; the indexes that the book gathers
	 * 	are asked of the report, that the book then takes from it.
	 */
	private static ReportConfig configFor(final BookEntry entry, final BookDefinition book){
		ReportConfig config = entry.config().withLanguage(book.language());
		if(book.indexes().contains(BookIndex.INDIVIDUALS))
			config = config.with(ReportOption.INDEX_INDIVIDUALS, true);
		if(book.indexes().contains(BookIndex.PLACES))
			config = config.with(ReportOption.INDEX_PLACES, true);
		return config;
	}


	/* ======================================================================
	 *                          Front matter
	 * ====================================================================== */

	/** The title, the subtitle and the author on a page (in the formats that split the document, the title page: what is before the first heading). */
	private static void appendTitlePage(final List<ReportSection> sections, final String title, final BookDefinition book){
		sections.add(new ReportSection.Paragraph("**" + title + "**"));
		if(!book.subtitle().isEmpty())
			sections.add(new ReportSection.Paragraph("*" + book.subtitle() + "*"));
		for(final String line : lines(book.author()))
			sections.add(new ReportSection.Paragraph(line));
		sections.add(ReportSection.PageBreak.INSTANCE);
	}

	private static void appendPreface(final List<ReportSection> sections, final ReportLabels labels, final BookDefinition book){
		addPageBreak(sections);
		sections.add(new ReportSection.Heading(1, (book.prefaceTitle().isEmpty()? labels.sections().preface(): book.prefaceTitle())));
		//(a paragraph with a new line is preformatted: the lines of a paragraph of the text are joined)
		final String text = StringUtils.remove(book.prefaceText(), '\r');
		for(final String paragraph : StringUtils.splitByWholeSeparator(text, "\n\n")){
			final String joined = StringUtils.replaceChars(paragraph, '\n', ' ').strip();
			if(!joined.isEmpty())
				sections.add(new ReportSection.Paragraph(joined));
		}
	}

	/** @return	The lines of the text that are not blank, stripped. */
	private static List<String> lines(final String text){
		final List<String> out = new ArrayList<>();
		for(final String line : StringUtils.split(StringUtils.remove(text, '\r'), '\n'))
			if(!line.isBlank())
				out.add(line.strip());
		return out;
	}

	/** Starts a new page, unless the book is at its start (a page break as the first section is the cover) or a page is already started. */
	private static void addPageBreak(final List<ReportSection> sections){
		if(!sections.isEmpty() && !(sections.getLast() instanceof ReportSection.PageBreak))
			sections.add(ReportSection.PageBreak.INSTANCE);
	}


	/* ======================================================================
	 *                          A report in the book
	 * ====================================================================== */

	/** What the indexes of the book are made of, taken from the reports as they are put in the book. */
	private static final class Harvest{

		/** The individuals by identifier (or by text, for one without): the cell of the person and the years. */
		private final Map<String, String[]> individuals = new LinkedHashMap<>();
		private final Set<String> places = new LinkedHashSet<>();
		private final Set<String> sources = new LinkedHashSet<>();
		private final Set<String> repositories = new LinkedHashSet<>();
		private boolean years;

	}

	/** What a report is telling at a point of its sections, for the part of it that the indexes use. */
	private enum Part{
		OTHER,
		INDIVIDUALS_INDEX,
		PLACES_INDEX,
		SOURCES,
		REPOSITORIES
	}

	/**
	 * Puts the report in the book as a chapter: a heading with its title, then its sections one level down. The indexes of the
	 * individuals and of the places are not put in the chapter if the book has them, but kept for the one of the book; the sources and the
	 * repositories stay in the chapter and their names are kept.
	 */
	private static void compose(final List<ReportSection> sections, final ReportDocument report, final BookEntry entry, final ReportLabels labels,
			final Set<BookIndex> indexes, final Harvest harvest){
		addPageBreak(sections);
		final String title = (StringUtils.isBlank(report.title())? entry.type().getTitle(): report.title());
		sections.add(new ReportSection.Heading(1, title));

		final String individualsIndex = labels.indexOfIndividuals();
		final String placesIndex = labels.indexOfPlaces();
		final String sources = labels.sections().sources();
		final String repositories = labels.sections().repositories();
		//the sources are headings of the second level, or of the third one when they are grouped by kind
		final int sourceLevel = (entry.config().groupSourcesByKind()? 3: 2);

		Part part = Part.OTHER;
		for(final ReportSection section : report.sections()){
			if(section instanceof ReportSection.Heading heading){
				if(heading.level() == 1){
					final String text = heading.text();
					if(indexes.contains(BookIndex.INDIVIDUALS) && text.equals(individualsIndex)){
						part = Part.INDIVIDUALS_INDEX;
						continue;
					}
					if(indexes.contains(BookIndex.PLACES) && text.equals(placesIndex)){
						part = Part.PLACES_INDEX;
						continue;
					}
					part = (text.equals(sources)? Part.SOURCES: (text.equals(repositories)? Part.REPOSITORIES: Part.OTHER));
				}
				else if(part == Part.SOURCES && heading.level() == sourceLevel)
					harvest.sources.add(heading.text());
				else if(part == Part.REPOSITORIES && heading.level() == 2)
					harvest.repositories.add(heading.text());

				sections.add(new ReportSection.Heading(Math.min(MAX_LEVEL, heading.level() + 1), heading.text()));
				continue;
			}

			//what is in an index of the book goes to it, and not to the chapter
			if(part == Part.INDIVIDUALS_INDEX || part == Part.PLACES_INDEX){
				if(section instanceof ReportSection.Table table){
					if(part == Part.INDIVIDUALS_INDEX)
						harvestIndividuals(table, labels, harvest);
					else
						for(final List<String> row : table.rows())
							if(!row.isEmpty() && !row.getFirst().isBlank())
								harvest.places.add(row.getFirst());
					continue;
				}
				//(the note of an index with nothing in it)
				if(section instanceof ReportSection.Paragraph)
					continue;
				part = Part.OTHER;
			}
			sections.add(section);
		}
	}

	private static void harvestIndividuals(final ReportSection.Table table, final ReportLabels labels, final Harvest harvest){
		final List<String> headers = table.headers();
		final int individual = headers.indexOf(labels.sections().columnIndividual());
		if(individual < 0)
			return;

		final int years = headers.indexOf(labels.sections().columnYears());
		for(final List<String> row : table.rows()){
			if(row.size() <= individual || row.get(individual).isBlank())
				continue;

			final String cell = row.get(individual);
			final String lifespan = (years >= 0 && row.size() > years? row.get(years): StringUtils.EMPTY);
			if(years >= 0)
				harvest.years = true;
			final String[] known = harvest.individuals.computeIfAbsent(idOf(cell), key -> new String[]{cell, lifespan});
			if(known[1].isEmpty() && !lifespan.isEmpty())
				known[1] = lifespan;
		}
	}

	/** @return	The identifier of the record a cell is about, the cell itself if it has none. */
	private static String idOf(final String cell){
		final Matcher linked = LINKED_ID.matcher(cell);
		if(linked.find())
			return linked.group(1);

		final Matcher bracketed = BRACKETED_ID.matcher(cell);
		return (bracketed.find()? bracketed.group(1): cell);
	}


	/* ======================================================================
	 *                          Indexes
	 * ====================================================================== */

	private static void appendIndexes(final List<ReportSection> sections, final FLEFModel model, final ReportLabels labels, final Locale locale,
			final Set<BookIndex> indexes, final Harvest harvest){
		final Comparator<String> collation = ReportCollation.of(locale);

		if(indexes.contains(BookIndex.INDIVIDUALS) && !harvest.individuals.isEmpty()){
			addPageBreak(sections);
			sections.add(new ReportSection.Heading(1, labels.indexOfIndividuals()));
			sections.add(individualsTable(model, labels, locale, harvest));
		}
		if(indexes.contains(BookIndex.PLACES))
			appendList(sections, labels.indexOfPlaces(), labels.sections().columnPlace(), harvest.places, collation);
		if(indexes.contains(BookIndex.SOURCES))
			appendList(sections, labels.sections().indexOfSources(), labels.sections().source(), harvest.sources, collation);
		if(indexes.contains(BookIndex.REPOSITORIES))
			appendList(sections, labels.sections().indexOfRepositories(), labels.sections().sourceRepository(), harvest.repositories, collation);
	}

	/** An index of one column, in the order of the language; nothing if there is nothing to list. */
	private static void appendList(final List<ReportSection> sections, final String heading, final String column, final Set<String> items,
			final Comparator<String> collation){
		if(items.isEmpty())
			return;

		final List<String> sorted = new ArrayList<>(items);
		sorted.sort(collation);
		final List<List<String>> rows = new ArrayList<>(sorted.size());
		for(final String item : sorted)
			rows.add(List.of(item));
		sections.add(new ReportSection.Heading(1, heading));
		sections.add(new ReportSection.Table(List.of(column), rows));
	}

	/** The individuals by family name, then by the other names, as the index of a report is, with the years of birth and death if a report had them. */
	private static ReportSection.Table individualsTable(final FLEFModel model, final ReportLabels labels, final Locale locale,
			final Harvest harvest){
		final Map<String, String> keys = new LinkedHashMap<>();
		for(final String id : harvest.individuals.keySet()){
			final FLEFRecord record = model.getRecordById(id);
			keys.put(id, (record != null? FamilyBookGenerator.sortName(record, locale): FamilyBookGenerator.NO_NAME));
		}
		final Comparator<String> collation = ReportCollation.of(locale);
		final List<String> ids = new ArrayList<>(harvest.individuals.keySet());
		ids.sort(Comparator.comparing((final String id) -> FamilyBookGenerator.NO_NAME.equals(keys.get(id)))
			.thenComparing(keys::get, collation)
			.thenComparing(Comparator.naturalOrder()));

		final List<String> headers = new ArrayList<>(2);
		headers.add(labels.sections().columnIndividual());
		if(harvest.years)
			headers.add(labels.sections().columnYears());
		final List<List<String>> rows = new ArrayList<>(ids.size());
		for(final String id : ids){
			final String[] person = harvest.individuals.get(id);
			rows.add(harvest.years? List.of(person[0], person[1]): List.of(person[0]));
		}
		return new ReportSection.Table(headers, rows);
	}

}
