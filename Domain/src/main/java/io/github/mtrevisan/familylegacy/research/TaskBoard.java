package io.github.mtrevisan.familylegacy.research;

import io.github.mtrevisan.familylegacy.io.model.FLEFModel;
import io.github.mtrevisan.familylegacy.io.model.readers.ResearchTaskReader;
import io.github.mtrevisan.familylegacy.io.model.record.FLEFRecord;
import org.apache.commons.lang3.StringUtils;
import org.apache.commons.lang3.Strings;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Collections;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;


/**
 * All the research tasks of a file, whatever their status, with what the task dashboard needs: the filters (status, priority, who
 * generated the task, the kind of record it is about, overdue, a text), the views (inbox, to do, done, all) and the counts that tell how
 * far the work is.
 * <p>
 * It only reads: the status of a task is changed by {@link OpenTasks#changeStatus(FLEFRecord, String)}.
 * </p>
 */
public final class TaskBoard{

	private TaskBoard(){}


	/**
	 * A task of the file.
	 *
	 * @param record     the research task
	 * @param description what is to be done, or {@code null}
	 * @param status     the status (never {@code null}: a task with none is {@code open})
	 * @param priority   the priority ({@code low}, {@code normal}, {@code high}): a task with none is {@code normal}
	 * @param due        the day it is due, or {@code null}
	 * @param rationale  why the task is proposed, or {@code null}
	 * @param outcome    what came out of it, or {@code null}
	 * @param origin     what generated the task (the key of the finding of the Research Assistant), or {@code null} if it was written by hand
	 * @param questions  the research questions the task serves (the visible ones that exist)
	 * @param relatedIds the records the task is about: the ones it names and the ones its questions are about
	 */
	public record Entry(FLEFRecord record, String description, String status, String priority, LocalDate due, String rationale,
			String outcome, String origin, List<FLEFRecord> questions, Set<String> relatedIds){

		/** @return whether the task is still to be done ({@code open} or {@code in_progress}) */
		public boolean isOpen(){
			return OpenTasks.isOpen(status);
		}

		/** @return whether the Research Assistant generated the task */
		public boolean isGenerated(){
			return (origin != null);
		}

		/** @return whether the task is still to be done and its due date is before {@code today} */
		public boolean isOverdue(final LocalDate today){
			return (isOpen() && due != null && due.isBefore(today));
		}

		/** @return whether the task is in the inbox: generated by the assistant and not yet taken in charge ({@code open}) */
		public boolean isInInbox(){
			return (isGenerated() && ResearchTaskReader.ENUM_STATUS_OPEN.equals(status));
		}

	}


	/** Who wrote the task. */
	public enum Origin{

		ANY,
		/** The Research Assistant generated it. */
		GENERATED,
		/** The researcher wrote it. */
		MANUAL

	}


	/** What the dashboard shows: a way of filtering the tasks that the user picks first. */
	public enum View{

		/** The tasks generated by the assistant and not yet taken in charge: the ones to accept or to dismiss. */
		INBOX,
		/** The tasks still to be done. */
		TO_DO,
		/** The tasks that are over: completed or abandoned. */
		DONE,
		ALL;


		/** @return the filter that shows what the view is about */
		public Filter filter(){
			return switch(this){
				case INBOX -> new Filter(Set.of(ResearchTaskReader.ENUM_STATUS_OPEN), null, Origin.GENERATED, false, null, null);
				case TO_DO -> new Filter(Set.of(ResearchTaskReader.ENUM_STATUS_OPEN, ResearchTaskReader.ENUM_STATUS_IN_PROGRESS), null,
					Origin.ANY, false, null, null);
				case DONE -> new Filter(Set.of(ResearchTaskReader.ENUM_STATUS_COMPLETED, ResearchTaskReader.ENUM_STATUS_ABANDONED), null,
					Origin.ANY, false, null, null);
				case ALL -> Filter.ALL;
			};
		}

	}


	/**
	 * What a task must be to be shown; the criteria that are empty let every task through.
	 *
	 * @param statuses    the statuses accepted (empty: any)
	 * @param priority    the priority accepted ({@code low}, {@code normal}, {@code high}), or {@code null} for any
	 * @param origin      who wrote the task (empty: any)
	 * @param overdueOnly whether only the tasks still to be done whose due date has passed are shown
	 * @param relatedType the type of record the task is about ({@code INDIVIDUAL}, {@code PLACE}...), or {@code null} for any
	 * @param text        a text that the description, the rationale or the outcome contains (any case), or {@code null}
	 */
	public record Filter(Set<String> statuses, String priority, Origin origin, boolean overdueOnly, String relatedType, String text){

		/** Every task. */
		public static final Filter ALL = new Filter(Set.of(), null, Origin.ANY, false, null, null);


		public Filter{
			statuses = Set.copyOf(statuses);
			origin = (origin != null? origin: Origin.ANY);
		}


		public Filter withStatuses(final Set<String> newStatuses){
			return new Filter(newStatuses, priority, origin, overdueOnly, relatedType, text);
		}

		public Filter withPriority(final String newPriority){
			return new Filter(statuses, StringUtils.trimToNull(newPriority), origin, overdueOnly, relatedType, text);
		}

		public Filter withOrigin(final Origin newOrigin){
			return new Filter(statuses, priority, newOrigin, overdueOnly, relatedType, text);
		}

		public Filter withOverdueOnly(final boolean newOverdueOnly){
			return new Filter(statuses, priority, origin, newOverdueOnly, relatedType, text);
		}

		public Filter withRelatedType(final String newRelatedType){
			return new Filter(statuses, priority, origin, overdueOnly, StringUtils.trimToNull(newRelatedType), text);
		}

		public Filter withText(final String newText){
			return new Filter(statuses, priority, origin, overdueOnly, relatedType, StringUtils.trimToNull(newText));
		}

		/**
		 * @param entry the task
		 * @param model the model, to know the type of the records the task is about
		 * @param today today
		 * @return whether the task passes
		 */
		public boolean matches(final Entry entry, final FLEFModel model, final LocalDate today){
			if(!statuses.isEmpty() && !statuses.contains(entry.status()))
				return false;
			if(priority != null && !priority.equalsIgnoreCase(entry.priority()))
				return false;
			if(origin == Origin.GENERATED && !entry.isGenerated() || origin == Origin.MANUAL && entry.isGenerated())
				return false;
			if(overdueOnly && !entry.isOverdue(today))
				return false;
			if(relatedType != null && !isAbout(entry, model))
				return false;
			return (text == null || Strings.CI.contains(entry.description(), text) || Strings.CI.contains(entry.rationale(), text)
				|| Strings.CI.contains(entry.outcome(), text));
		}

		private boolean isAbout(final Entry entry, final FLEFModel model){
			for(final String id : entry.relatedIds()){
				final FLEFRecord record = model.getRecordById(id);
				if(record != null && relatedType.equalsIgnoreCase(record.getTag()))
					return true;
			}
			return false;
		}

	}


	/**
	 * How far the work is.
	 *
	 * @param total      all the tasks
	 * @param open       the ones not yet started
	 * @param inProgress the ones under way
	 * @param completed  the ones completed
	 * @param abandoned  the ones given up
	 * @param overdue    the ones still to be done whose due date has passed
	 * @param inbox      the ones generated by the assistant and waiting to be accepted or dismissed
	 */
	public record Statistics(int total, int open, int inProgress, int completed, int abandoned, int overdue, int inbox){

		/** @return the share of the tasks that were completed, among the ones not abandoned (0 to 1; 0 if there is none) */
		public double completion(){
			final int pursued = total - abandoned;
			return (pursued > 0? (double)completed / pursued: 0.);
		}

	}


	/**
	 * @param model the model
	 * @return the visible tasks, whatever their status, in the order of the file
	 */
	public static List<Entry> list(final FLEFModel model){
		final Map<String, FLEFRecord> questionsById = new HashMap<>();
		for(final FLEFRecord question : ResearchHelper.listQuestions(model))
			questionsById.put(question.getId(), question);

		final List<Entry> entries = new ArrayList<>();
		for(final FLEFRecord record : ResearchHelper.listTasks(model)){
			final List<FLEFRecord> questions = new ArrayList<>();
			final Set<String> relatedIds = new LinkedHashSet<>(OpenTasks.relatedIds(record));
			for(final String questionId : OpenTasks.references(record, ResearchTaskReader.TAG_QUESTION)){
				final FLEFRecord question = questionsById.get(questionId);
				if(question != null && !questions.contains(question)){
					questions.add(question);
					relatedIds.addAll(OpenTasks.targetIds(question));
				}
			}

			final String status = StringUtils.defaultIfBlank(StringUtils.strip(ResearchHelper.status(record)),
				ResearchTaskReader.ENUM_STATUS_OPEN);
			final String priority = StringUtils.defaultIfBlank(StringUtils.strip(ResearchHelper.taskPriority(record)),
				ResearchTaskReader.ENUM_PRIORITY_NORMAL);
			entries.add(new Entry(record, ResearchHelper.taskDescription(record), status.toLowerCase(Locale.ROOT),
				priority.toLowerCase(Locale.ROOT),
				OpenTasks.parseDue(ResearchHelper.firstTextValue(record, ResearchTaskReader.TAG_DUE_DATE)),
				StringUtils.trimToNull(ResearchHelper.firstTextValue(record, ResearchTaskReader.TAG_RATIONALE)),
				StringUtils.trimToNull(ResearchHelper.firstTextValue(record, ResearchTaskReader.TAG_OUTCOME)),
				StringUtils.trimToNull(ResearchHelper.firstTextValue(record, ResearchTaskReader.TAG_ASSISTANT_FINDING_ID)),
				Collections.unmodifiableList(questions), Collections.unmodifiableSet(relatedIds)));
		}
		return entries;
	}

	/**
	 * @param entries the tasks
	 * @param filter  what they must be
	 * @param model   the model
	 * @param today   today
	 * @return the tasks that pass, the ones still to be done first: by due date (the earliest first, the undated last), then by
	 * priority (the highest first), then by description
	 */
	public static List<Entry> filter(final List<Entry> entries, final Filter filter, final FLEFModel model, final LocalDate today){
		final List<Entry> shown = new ArrayList<>();
		for(final Entry entry : entries)
			if(filter.matches(entry, model, today))
				shown.add(entry);
		shown.sort(Comparator.comparing((Entry entry) -> !entry.isOpen())
			.thenComparing(Entry::due, Comparator.nullsLast(Comparator.naturalOrder()))
			.thenComparingInt(entry -> OpenTasks.priorityRank(entry.priority()))
			.thenComparing(entry -> StringUtils.defaultString(entry.description()), String.CASE_INSENSITIVE_ORDER)
			.thenComparing(entry -> StringUtils.defaultString(entry.record().getId())));
		return shown;
	}

	/**
	 * @param entries the tasks
	 * @param today   today
	 * @return how far the work is
	 */
	public static Statistics statistics(final List<Entry> entries, final LocalDate today){
		int open = 0;
		int inProgress = 0;
		int completed = 0;
		int abandoned = 0;
		int overdue = 0;
		int inbox = 0;
		for(final Entry entry : entries){
			switch(entry.status()){
				case ResearchTaskReader.ENUM_STATUS_IN_PROGRESS -> inProgress ++;
				case ResearchTaskReader.ENUM_STATUS_COMPLETED -> completed ++;
				case ResearchTaskReader.ENUM_STATUS_ABANDONED -> abandoned ++;
				default -> open ++;
			}
			if(entry.isOverdue(today))
				overdue ++;
			if(entry.isInInbox())
				inbox ++;
		}
		return new Statistics(entries.size(), open, inProgress, completed, abandoned, overdue, inbox);
	}

	/**
	 * @param model the model
	 * @return what generated the tasks of the file, hidden ones included, whatever their status: a finding that already became a task
	 * is not proposed again, even if the task is over
	 */
	public static Set<String> origins(final FLEFModel model){
		final Set<String> origins = new LinkedHashSet<>();
		for(final FLEFRecord record : model.getRecordsByType(ResearchTaskReader.TYPE)){
			final String origin = StringUtils.trimToNull(ResearchHelper.firstTextValue(record, ResearchTaskReader.TAG_ASSISTANT_FINDING_ID));
			if(origin != null)
				origins.add(origin);
		}
		return origins;
	}

}
